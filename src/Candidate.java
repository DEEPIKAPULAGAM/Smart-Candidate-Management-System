//represents a candidate and stores candidate details
public class Candidate {

    private int id;

    private String name;
    private String email;
    private String phone;

    private String college;
    private String branch;

    private int graduationYear;
    private double cgpa;

    private String skills;

    private int experienceYears;

    // No-argument constructor
    public Candidate() {
    }

    // Constructor for retrieving existing candidates from the database
    public Candidate(int id,String name,String email,String phone,String college,String branch,int graduationYear,double cgpa,String skills,int experienceYears){
        this.id = id;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.college = college;
        this.branch = branch;
        this.graduationYear = graduationYear;
        this.cgpa = cgpa;
        this.skills = skills;
        this.experienceYears = experienceYears;
    }

    // Constructor overloading: used when adding a new candidate
    // ID is not required because it is generated by the database
    public Candidate(String name, String email, String phone,
                     String college, String branch, int graduationYear,
                     double cgpa, String skills, int experienceYears) {

        // Calls the existing constructor with an initial ID of 0
        this(0, name, email, phone, college, branch,
             graduationYear, cgpa, skills, experienceYears);
    }


    public int getId(){
        return id;
    }
    public void setId(int id){
        this.id = id;
    }

    // Name
    public String getName(){
        return name;
    }
    public void setName(String name){
        this.name = name;
    }

    // Email
    public String getEmail(){
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    // Phone
    public String getPhone(){
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    // College
    public String getCollege(){
        return college;
    }
    public void setCollege(String college){
        this.college = college;
    }

    // Branch
    public String getBranch(){
        return branch;
    }
    public void setBranch(String branch){
        this.branch = branch;
    }

    // Graduation year
    public int getGraduationYear(){
        return graduationYear;
    }
    public void setGraduationYear(int graduationYear){
        this.graduationYear = graduationYear;
    }

    // CGPA
    public double getCgpa(){
        return cgpa;
    }
    public void setCgpa(double cgpa){
        this.cgpa = cgpa;
    }

    // Skills
    public String getSkills(){
        return skills;
    }
    public void setSkills(String skills){
        this.skills = skills;
    }

    // Experience years
    public int getExperienceYears(){
        return experienceYears;
    }
    public void setExperienceYears(int experienceYears){
        this.experienceYears = experienceYears;
    }

    // Overrides Object class's toString() method to display candidate details
    // Allows us to directly use System.out.println(candidate)
    @Override
    public String toString() {
        return "Candidate ID: " + id +
                "\nName: " + name +
                "\nEmail: " + email +
                "\nPhone: " + phone +
                "\nCollege: " + college +
                "\nBranch: " + branch +
                "\nGraduation Year: " + graduationYear +
                "\nCGPA: " + cgpa +
                "\nSkills: " + skills +
                "\nExperience: " + experienceYears + " years";
    }

}